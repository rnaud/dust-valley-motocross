// Axis-angle construction from 0x4b7d90. Temporaries preserve instruction
// order and asymmetric float32 stores; trig equivalence requires oracle checks.
export function mcmAxisAngleMatrix(axis, angle) {
  const t0 = axis[0] * axis[0];
  const t1 = axis[1] * axis[1];
  const t2 = axis[2] * axis[2];
  const t3 = t0 + t1;
  const t4 = t3 + t2;
  const t5 = Math.sqrt(t4);
  const t6 = axis[0] / t5;
  const t7 = axis[1] / t5;
  const t8 = axis[2] / t5;
  const t9 = Math.cos(angle);
  const t10 = Math.sin(angle);
  const t11 = 1 - t9;
  const t12 = t6 * t6;
  const t13 = t12 * t11;
  const t14 = t13 + t9;
  const t15 = Math.fround(t14);
  const t16 = t6 * t7;
  const t17 = t16 * t11;
  const t18 = Math.fround(t17);
  const t19 = t8 * t10;
  const t20 = Math.fround(t19);
  const t21 = t19 + t18;
  const t22 = Math.fround(t21);
  const t23 = t6 * t11;
  const t24 = t23 * t8;
  const t25 = Math.fround(t24);
  const t26 = t7 * t10;
  const t27 = Math.fround(t26);
  const t28 = t25 - t26;
  const t29 = Math.fround(t28);
  const t30 = t18 - t20;
  const t31 = Math.fround(t30);
  const t32 = t7 * t7;
  const t33 = t32 * t11;
  const t34 = t10 * t6;
  const t35 = t33 + t9;
  const t36 = Math.fround(t35);
  const t37 = t7 * t11;
  const t38 = t37 * t8;
  const t39 = t38 + t34;
  const t40 = t25 + t27;
  const t41 = t8 * t8;
  const t42 = Math.fround(t39);
  const t43 = t41 * t11;
  const t44 = Math.fround(t40);
  const t45 = t38 - t34;
  const t46 = Math.fround(t45);
  const t47 = t43 + t9;
  const t48 = Math.fround(t47);
  return [t15, t22, t29, 0, t31, t36, t42, 0, t44, t46, t48, 0, 0, 0, 0, 1];
}
